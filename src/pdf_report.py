#!/usr/bin/env python3
"""
PDF Report Generator
Shared module: copy into the src/ folder of every tool that makes PDF reports.
"""

from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
)
from reportlab.lib.enums import TA_CENTER

SEVERITY_COLORS = {
    "Critical": colors.HexColor("#C0392B"),
    "High": colors.HexColor("#E74C3C"),
    "Medium": colors.HexColor("#F39C12"),
    "Low": colors.HexColor("#3498DB"),
    "Info": colors.HexColor("#7F8C8D"),
}
SEVERITY_ORDER = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3, "Info": 4}


def _styles():
    s = getSampleStyleSheet()
    s.add(ParagraphStyle(name="ReportTitle", fontSize=22, leading=26,
                         textColor=colors.HexColor("#1A1A2E"), spaceAfter=6,
                         alignment=TA_CENTER, fontName="Helvetica-Bold"))
    s.add(ParagraphStyle(name="ReportSubtitle", fontSize=11, leading=14,
                         textColor=colors.HexColor("#555555"),
                         alignment=TA_CENTER, spaceAfter=20))
    s.add(ParagraphStyle(name="SectionHeading", fontSize=14, leading=18,
                         textColor=colors.white,
                         backColor=colors.HexColor("#1A1A2E"),
                         spaceBefore=14, spaceAfter=10, leftIndent=6,
                         fontName="Helvetica-Bold", borderPadding=(6, 6, 6, 6)))
    s.add(ParagraphStyle(name="FindingTitle", fontSize=11, leading=14,
                         fontName="Helvetica-Bold", spaceAfter=2))
    s.add(ParagraphStyle(name="FindingDetail", fontSize=9.5, leading=13,
                         textColor=colors.HexColor("#333333"),
                         fontName="Courier", spaceAfter=10))
    s.add(ParagraphStyle(name="MetaLabel", fontSize=9,
                         textColor=colors.HexColor("#777777"),
                         fontName="Helvetica-Bold"))
    s.add(ParagraphStyle(name="MetaValue", fontSize=9,
                         textColor=colors.HexColor("#222222")))
    s.add(ParagraphStyle(name="FooterNote", fontSize=8,
                         textColor=colors.HexColor("#999999"),
                         alignment=TA_CENTER))
    return s


def _esc(text):
    return (str(text).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;"))


def _badge(severity, styles):
    color = SEVERITY_COLORS.get(severity, colors.grey)
    return Paragraph(f'<font color="#{color.hexval()[2:]}"><b>[{severity.upper()}]</b></font>',
                     styles["FindingTitle"])


def _summary_table(findings):
    order = ["Critical", "High", "Medium", "Low", "Info"]
    counts = {k: 0 for k in order}
    for f in findings:
        sev = f.get("severity", "Info")
        counts[sev] = counts.get(sev, 0) + 1
    table = Table([order + ["Total"],
                   [str(counts[k]) for k in order] + [str(len(findings))]],
                  colWidths=[0.85 * inch] * 6)
    style = [(("BACKGROUND", (i, 0), (i, 0), SEVERITY_COLORS[k]))
             for i, k in enumerate(order)]
    style += [
        ("BACKGROUND", (5, 0), (5, 0), colors.HexColor("#1A1A2E")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CCCCCC")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.white),
    ]
    table.setStyle(TableStyle(style))
    return table


def generate_pdf_report(report_data, output_path, report_title="Security Scan Report"):
    """
    report_data keys: tool_name, target, scan_date (ISO), findings (list of dicts
    with type/severity/detail and optional url/source_ip/line/timestamp),
    extra_meta (optional list of (label, value)).
    """
    styles = _styles()
    findings = report_data.get("findings", [])
    ordered = sorted(findings,
                     key=lambda f: SEVERITY_ORDER.get(f.get("severity", "Info"), 5))

    doc = SimpleDocTemplate(output_path, pagesize=letter,
                            topMargin=0.6 * inch, bottomMargin=0.6 * inch,
                            leftMargin=0.6 * inch, rightMargin=0.6 * inch)
    story = [
        Paragraph(_esc(report_title), styles["ReportTitle"]),
        Paragraph(f"Generated by {_esc(report_data.get('tool_name', 'Security Tool'))}",
                  styles["ReportSubtitle"]),
        HRFlowable(width="100%", color=colors.HexColor("#1A1A2E"), thickness=1.2),
        Spacer(1, 14),
    ]

    try:
        date_display = datetime.fromisoformat(report_data["scan_date"]).strftime("%Y-%m-%d %H:%M:%S")
    except (KeyError, ValueError, TypeError):
        date_display = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    meta = [("Target / Source:", report_data.get("target", "N/A")),
            ("Scan Date:", date_display),
            ("Total Findings:", len(findings))]
    meta += report_data.get("extra_meta", [])
    meta_table = Table([[Paragraph(l, styles["MetaLabel"]),
                         Paragraph(_esc(v), styles["MetaValue"])] for l, v in meta],
                       colWidths=[1.6 * inch, 5.4 * inch])
    meta_table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
    story += [meta_table, Spacer(1, 16),
              Paragraph("SEVERITY SUMMARY", styles["SectionHeading"]),
              Spacer(1, 6), _summary_table(findings), Spacer(1, 20),
              Paragraph("DETAILED FINDINGS", styles["SectionHeading"]),
              Spacer(1, 8)]

    if not ordered:
        story.append(Paragraph("No findings were identified.", styles["Normal"]))
    for idx, f in enumerate(ordered, 1):
        row = Table([[Paragraph(f"{idx}. {_esc(f.get('type', 'Unknown'))}", styles["FindingTitle"]),
                      _badge(f.get("severity", "Info"), styles)]],
                    colWidths=[5.0 * inch, 2.0 * inch])
        row.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                                 ("ALIGN", (1, 0), (1, 0), "RIGHT")]))
        story.append(row)
        bits = []
        if f.get("url"):
            bits.append(f"URL: {f['url']}")
        if f.get("source_ip"):
            bits.append(f"Source IP: {f['source_ip']}")
        if f.get("line") is not None:
            bits.append(f"Line: {f['line']}")
        if f.get("timestamp"):
            bits.append(f"Time: {f['timestamp']}")
        if bits:
            story.append(Paragraph(_esc(" | ".join(bits)), styles["MetaValue"]))
        story += [Paragraph(_esc(f.get("detail", "")), styles["FindingDetail"]),
                  HRFlowable(width="100%", color=colors.HexColor("#E0E0E0"), thickness=0.5),
                  Spacer(1, 8)]

    story += [Spacer(1, 24),
              HRFlowable(width="100%", color=colors.HexColor("#CCCCCC"), thickness=0.5),
              Spacer(1, 6),
              Paragraph(f"Report generated on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} | "
                        f"For authorized security testing and review purposes only.",
                        styles["FooterNote"])]
    doc.build(story)
    return output_path
